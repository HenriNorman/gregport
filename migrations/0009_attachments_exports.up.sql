-- Direct-to-storage attachments need an upload lifecycle on top of the
-- original attachment row: pending until the client uploads, uploaded once the
-- object is confirmed, quarantined when the bytes do not match the declared
-- type, and deleted by retention.
ALTER TABLE attachments
  ADD COLUMN upload_status    text NOT NULL DEFAULT 'pending',
  ADD COLUMN confirmed_at     timestamptz,
  ADD COLUMN expires_at       timestamptz,
  ADD COLUMN thumbnail_key    text,
  ADD COLUMN checksum         text,
  ADD COLUMN quarantine_reason text,
  ADD COLUMN updated_at       timestamptz NOT NULL DEFAULT now();

ALTER TABLE attachments
  ADD CONSTRAINT attachments_upload_status_check
  CHECK (upload_status IN ('pending', 'uploaded', 'quarantined', 'deleted'));

-- Object keys are generated by the server and must be unique.
CREATE UNIQUE INDEX idx_attachments_storage_key ON attachments (storage_key);

-- Housekeeping scans expired pending uploads and the confirm/download paths
-- look attachments up by id within an org.
CREATE INDEX idx_attachments_org_status_expires
  ON attachments (org_id, upload_status, expires_at);

-- Asynchronous CSV exports. The worker streams rows into object storage and
-- records the object key when it finishes.
CREATE TABLE export_jobs (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id       uuid NOT NULL REFERENCES organizations(id),
  requested_by uuid NOT NULL REFERENCES users(id),
  status       text NOT NULL DEFAULT 'pending',
  storage_key  text,
  filters      jsonb NOT NULL DEFAULT '{}'::jsonb,
  error        text,
  row_count    bigint,
  created_at   timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CONSTRAINT export_jobs_status_check
    CHECK (status IN ('pending', 'running', 'done', 'failed'))
);

CREATE INDEX idx_export_jobs_org_created
  ON export_jobs (org_id, created_at DESC);

CREATE INDEX idx_export_jobs_status
  ON export_jobs (status);
